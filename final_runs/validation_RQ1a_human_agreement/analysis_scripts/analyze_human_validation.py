def generate_table2(df: pd.DataFrame, output_path: Path):
    """Generate human_validation_confusion_table.tex - proper 3x3 confusion matrix"""
    total_n = len(df)
    
    # Build 3x3 confusion matrix: rows = Human, columns = LLM
    # Categories: 0.0 = Not supported, 0.5 = Partially, 1.0 = Fully
    categories = [0.0, 0.5, 1.0]
    cat_labels = {0.0: "Not supported", 0.5: "Partially", 1.0: "Fully"}
    
    matrix = np.zeros((3, 3), dtype=int)
    for _, row in df.iterrows():
        human_idx = categories.index(row['Human_Score'])
        llm_idx = categories.index(row['LLM_Score'])
        matrix[human_idx, llm_idx] += 1
    
    lines = [
        "% Table: Human Validation - Confusion Matrix: LLM Judge vs Human Expert",
        "% Generated by: final_runs/validation_RQ1a_human_agreement/analysis_scripts/analyze_human_validation.py",
        r"\begin{table}[H]",
        r"\centering",
        f"\\caption{{Confusion Matrix: LLM Judge vs.\\ Human Expert (Combined, n={total_n})}}",
        r"\label{tab:human_validation_confusion}",
        r"\begin{threeparttable}",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r" & \textbf{LLM: Not supported} & \textbf{LLM: Partially} & \textbf{LLM: Fully} \\",
        r"\midrule",
    ]
    
    row_labels = ["Human: Not supported", "Human: Partially", "Human: Fully"]
    for i, row_label in enumerate(row_labels):
        cells = []
        for j in range(3):
            count = matrix[i, j]
            pct = count / total_n * 100
            cells.append(f"{count} ({pct:.1f}\\%)")
        lines.append(f"\\textbf{{{row_label}}} & {cells[0]} & {cells[1]} & {cells[2]} \\\\")
    
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\begin{tablenotes}",
        r"\small",
        r"\item \textit{Note.} Rows = human expert verdicts; columns = LLM judge verdicts.",
        r"\end{tablenotes}",
        r"\end{threeparttable}",
        r"\end{table}",
    ])
    
    output_path.write_text('\n'.join(lines) + '\n')
    print(f"Generated: {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Analyze human validation results")
    parser.add_argument("--output", type=str, help="Output directory for tables")
    parser.add_argument("--confusion-output", type=str, help="Output path for confusion table")
    args = parser.parse_args()
    
    script_dir = Path(__file__).parent
    data_dir = script_dir.parent / "Data"
    
    # Load data
    xlsx_path = data_dir / "combined_human_validation_results.xlsx"
    if not xlsx_path.exists():
        raise FileNotFoundError(f"Data file not found: {xlsx_path}")
    
    df = pd.read_excel(xlsx_path, engine='openpyxl')
    print(f"Loaded {len(df)} rows from {xlsx_path}")
    
    # Analyze by source
    results = analyze_by_source(df)
    
    # Compute combined stats
    llm_scores = df['LLM_Score'].values
    human_scores = df['Human_Score'].values
    combined_kappa = compute_cohens_kappa(llm_scores, human_scores)
    combined_agreement = (llm_scores == human_scores).mean() * 100
    r, p_value = stats.pearsonr(llm_scores, human_scores)
    if p_value < 0.001:
        combined_r_str = f"{r:.3f}***"
    elif p_value < 0.01:
        combined_r_str = f"{r:.3f}**"
    else:
        combined_r_str = f"{r:.3f}"
    
    combined_stats = {
        'n': len(df),
        'kappa': combined_kappa,
        'agreement': combined_agreement,
        'pearson_r': combined_r_str
    }
    
    print(f"\nResults by source:")
    for r in results:
        print(f"  {r['dataset']}: n={r['n']}, κ={r['kappa']:.3f}, agreement={r['agreement']:.1f}%")
    print(f"\nCombined: n={combined_stats['n']}, κ={combined_stats['kappa']:.3f}, agreement={combined_stats['agreement']:.1f}%")
    
    # Compute confusion matrix
    confusion = compute_confusion(df)
    total_disagreements = sum(confusion.values())
    print(f"\nDisagreements: {total_disagreements} ({total_disagreements/len(df)*100:.1f}%)")
    for k, v in confusion.items():
        if v > 0:
            print(f"  {k}: {v}")
    
    # Generate tables
    if args.output:
        output_path = Path(args.output)
    else:
        output_path = script_dir.parent / "human_validation_table.tex"
    
    if args.confusion_output:
        confusion_output_path = Path(args.confusion_output)
    else:
        confusion_output_path = script_dir.parent / "human_validation_confusion_table.tex"
    
    generate_table1(results, combined_stats, output_path)
    generate_table2(df, confusion_output_path)
    
    print("\nDone!")


if __name__ == "__main__":
    main()

