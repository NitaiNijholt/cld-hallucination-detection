#!/usr/bin/env python3
"""
Analyze Human Validation Results: LLM Judge vs Expert Agreement

Generates:
- human_validation_table.tex: Inter-rater agreement by dataset
- human_validation_confusion_table.tex: Confusion matrix of disagreements

Data source: combined_human_validation_results.xlsx
"""

import argparse
from pathlib import Path
import pandas as pd
import numpy as np
from scipy import stats


def compute_cohens_kappa(y1: np.ndarray, y2: np.ndarray) -> float:
    """Compute Cohen's Kappa for ordinal data."""
    # Get unique categories
    categories = sorted(set(y1) | set(y2))
    n = len(y1)
    
    # Build confusion matrix
    k = len(categories)
    matrix = np.zeros((k, k))
    cat_to_idx = {c: i for i, c in enumerate(categories)}
    
    for a, b in zip(y1, y2):
        matrix[cat_to_idx[a], cat_to_idx[b]] += 1
    
    # Compute observed agreement
    p_o = np.trace(matrix) / n
    
    # Compute expected agreement
    row_sums = matrix.sum(axis=1)
    col_sums = matrix.sum(axis=0)
    p_e = np.sum(row_sums * col_sums) / (n * n)
    
    # Cohen's Kappa
    if p_e == 1:
        return 1.0
    kappa = (p_o - p_e) / (1 - p_e)
    return kappa


def analyze_by_source(df: pd.DataFrame) -> list:
    """Analyze each source file separately."""
    results = []
    
    source_info = {
        'File1_MIck_1': ('File 1 (Depressive Symptoms)', 'GPT-4.1'),
        'File2_Claude4Sonnet': ('File 2 (Depressive Symptoms)', 'Claude 4 Sonnet'),
        'File3_ResultExcel': ('File 3 (Social Norms)', 'GPT-4.1'),
    }
    
    for source in df['Source'].unique():
        subset = df[df['Source'] == source]
        n = len(subset)
        
        llm_scores = subset['LLM_Score'].values
        human_scores = subset['Human_Score'].values
        
        # Cohen's Kappa
        kappa = compute_cohens_kappa(llm_scores, human_scores)
        
        # Agreement (exact match)
        agreement = (llm_scores == human_scores).mean() * 100
        
        # Pearson correlation
        if np.std(llm_scores) > 0 and np.std(human_scores) > 0:
            r, p_value = stats.pearsonr(llm_scores, human_scores)
            if p_value < 0.001:
                r_str = f"{r:.3f}***"
            elif p_value < 0.01:
                r_str = f"{r:.3f}**"
            elif p_value < 0.05:
                r_str = f"{r:.3f}*"
            else:
                r_str = f"{r:.3f}"
        else:
            r_str = "---"
        
        dataset, generator = source_info.get(source, (source, 'Unknown'))
        results.append({
            'dataset': dataset,
            'generator': generator,
            'n': n,
            'kappa': kappa,
            'agreement': agreement,
            'pearson_r': r_str
        })
    
    return results


def compute_confusion(df: pd.DataFrame) -> dict:
    """Compute confusion matrix of disagreements."""
    confusion = {
        'LLM Fully, Human Partially': 0,
        'LLM Fully, Human Not': 0,
        'LLM Partially, Human Fully': 0,
        'LLM Partially, Human Not': 0,
        'LLM Not, Human Fully': 0,
        'LLM Not, Human Partially': 0,
    }
    
    for _, row in df.iterrows():
        llm = row['LLM_Score']
        human = row['Human_Score']
        
        if llm == human:
            continue
        
        if llm == 1.0 and human == 0.5:
            confusion['LLM Fully, Human Partially'] += 1
        elif llm == 1.0 and human == 0.0:
            confusion['LLM Fully, Human Not'] += 1
        elif llm == 0.5 and human == 1.0:
            confusion['LLM Partially, Human Fully'] += 1
        elif llm == 0.5 and human == 0.0:
            confusion['LLM Partially, Human Not'] += 1
        elif llm == 0.0 and human == 1.0:
            confusion['LLM Not, Human Fully'] += 1
        elif llm == 0.0 and human == 0.5:
            confusion['LLM Not, Human Partially'] += 1
    
    return confusion


